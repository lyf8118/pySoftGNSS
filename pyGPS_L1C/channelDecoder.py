#%% BCH decoder
class BCHDecoder:
    """Decode the BCH(51, 8) symbols in CNAV-2 subframe 1."""

    @staticmethod
    def BCH51_8Decoding(bits):
        """Decode the BCH(51, 8) data symbols of CNAV-2 subframe 1.

        A total of 2^8 hypotheses are tested to recover the nine TOI bits.
        The sign of the largest correlation supplies the ninth bit.

        Args
        ----
            bits        - ndarray
                        Fifty-two bipolar ``(-1, +1)`` input symbols.
        Returns
        -------
            flag        - int
                        One for successful decoding and zero otherwise.
            decodedBits - ndarray
                        Nine decoded TOI bits, or an empty array on failure.
        """
        # Generate the 2^8 possible BCH(51,8) codewords.
        hypothesisBits = np.empty((256, 8), dtype=np.int8)
        hypothesisSymbols = np.empty((256, 52), dtype=np.int8)
        for hypothesis in range(256):
            informationBits = np.array(
                [int(bit) for bit in f"{hypothesis:08b}"], dtype=np.int8)
            hypothesisBits[hypothesis] = informationBits
            register = informationBits[::-1].copy()
            sequence = np.empty(51, dtype=np.int8)
            for index in range(51):
                sequence[index] = register[7]
                feedback = np.bitwise_xor.reduce(
                    register[[0, 3, 4, 5, 6, 7]])
                register[1:] = register[:-1]
                register[0] = feedback
            hypothesisSymbols[hypothesis] = 1 - 2 * np.r_[0, sequence]

        # Select the codeword having the largest absolute correlation.
        correValue = hypothesisSymbols @ np.asarray(bits)
        pos = int(np.argmax(np.abs(correValue)))
        if abs(correValue[pos]) < 40:
            return 0, np.empty(0, dtype=np.int8)
        b9 = int(correValue[pos] < 0)
        return 1, np.r_[b9, hypothesisBits[pos]]


